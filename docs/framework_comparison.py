"""
多智能体框架对比分析

AutoGen vs LangGraph 可视化能力比较
"""

# AutoGen 优势:
# 1. 内置对话可视化 - 自动记录智能体间的对话历史
# 2. 简单的聊天界面 - 易于实现实时对话显示
# 3. 内置Gradio/Streamlit集成 - 快速构建UI
# 4. 对话流程清晰 - 轮次制对话，易于跟踪
# 5. 丰富的可视化示例和文档

# LangGraph 优势:
# 1. 工作流可视化 - 支持复杂的有向图可视化
# 2. 状态管理 - 更好的状态跟踪和可视化
# 3. 自定义节点 - 灵活的工作流设计
# 4. 条件分支 - 复杂决策流程的可视化
# 5. 与LangSmith集成 - 专业的调试和监控

# 推荐: 结合使用
# - AutoGen: 智能体对话和实时交互
# - LangGraph: 工作流编排和状态管理
